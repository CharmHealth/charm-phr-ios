func UIColorFromRGB(rgbValueWithAlpha:UInt) -> UIColor
{
    return UIColor(
        red: CGFloat((rgbValueWithAlpha & 0xFF000000) >> 24) / 255.0,
        green: CGFloat((rgbValueWithAlpha & 0x00FF0000) >> 16) / 255.0,
        blue: CGFloat((rgbValueWithAlpha & 0x0000FF00) >> 8) / 255.0,
        alpha: CGFloat(rgbValueWithAlpha & 0x000000FF) / 255.0
    )
}

func makeInsuranceValidDateTxt(startDate: Date , endDate: Date) -> NSAttributedString{
    
    
    let fromDateStr = startDate.getStringFromDate(dateFormat: PHR_DATE_DISPLAY_FORMAT_WITH_YEAR)
    let toDateStr = endDate.getStringFromDate(dateFormat: PHR_DATE_DISPLAY_FORMAT_WITH_YEAR)
    
    let text = getString(key: "com.charmphr.insurance.date.msg", with: [ fromDateStr, toDateStr  ])
    let attributedString = NSMutableAttributedString(string: text)
    

    let mediumFontAtributes = [NSAttributedString.Key.font : UIFont.systemFont(ofSize: FONT_SIZE_NORMAL, Weight: .semibold) , NSAttributedString.Key.foregroundColor : UIColorFromRGB(rgbValueWithAlpha: TEXT_COLOR_HEAVYDARK)]
    
    let normalFontAtributes = [NSAttributedString.Key.font : UIFont.systemFont(ofSize: FONT_SIZE_NORMAL, Weight: .regular), NSAttributedString.Key.foregroundColor : UIColorFromRGB(rgbValueWithAlpha: TEXT_COLOR_BLACK70)]

    
    attributedString.addAttributes(normalFontAtributes, range: NSRange(location: 0, length: 11))
    attributedString.addAttributes(mediumFontAtributes, range: NSRange(location: 11, length: fromDateStr.count))
    attributedString.addAttributes(normalFontAtributes, range: NSRange(location: fromDateStr.count + 11, length: 12))
    attributedString.addAttributes(mediumFontAtributes, range: NSRange(location: fromDateStr.count + 24, length: toDateStr.count))

    
    return attributedString
}

func formMemberNameFrom(fullName:String, prefix: String , degree: String? = nil) -> String{
    var memberName = fullName
    
    
    if prefix.isNotBlank()  && prefix.lowercased() != "null" && prefix.lowercased() != "dr." {
        memberName = "\(prefix). \(memberName)"
    }
    
     
    if (!degree.isNilOrBlank() && memberName.isNotBlank()) {
        
        var degreeVal = degree ?? ""
        degreeVal = degreeVal.components(separatedBy: "-").firstOrNil() ?? ""
        
        memberName = "\(memberName), \(degreeVal)"
    }
    
    return memberName
}
